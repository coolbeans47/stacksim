#!/usr/bin/env node
// Regenerates the AWS SAM data tables under src/cloudformation/sam/generated/
// from a pinned aws/serverless-application-model release:
//   - policy-templates.ts: the policy templates whose actions target services
//     StackSim implements, plus the names of every other template;
//   - managed-policies.ts: AWS managed policy names and their IAM paths;
//   - schema.ts: every property, event type, and Globals key in the SAM schema.
// The tables are data derived from SAM's Apache-2.0 sources; the translator
// itself is not embedded. Usage: node scripts/generate-sam-tables.mjs [tag]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const tag = process.argv[2] ?? "v1.115.0";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "src", "cloudformation", "sam", "generated");
const base = `https://raw.githubusercontent.com/aws/serverless-application-model/${tag}/samtranslator`;

/** Service prefixes of the services StackSim implements (sam-transform-design.md SAM-02). */
const IMPLEMENTED_SERVICES = new Set(["dynamodb", "sqs", "sns", "s3", "lambda", "states", "events", "ssm", "secretsmanager", "cloudwatch", "logs", "ses", "xray", "cloudformation"]);

async function fetchJson(path) {
  const response = await fetch(`${base}/${path}`);
  if (!response.ok) throw new Error(`GET ${path} failed with ${response.status}`);
  return response.json();
}

function actionServices(value, services = new Set()) {
  if (Array.isArray(value)) value.forEach(item => actionServices(item, services));
  else if (value && typeof value === "object") {
    for (const [key, item] of Object.entries(value)) {
      if (key === "Action") for (const action of [item].flat()) services.add(String(action).split(":")[0]);
      else actionServices(item, services);
    }
  }
  return services;
}

const header = (source) => `// Generated by scripts/generate-sam-tables.mjs from aws/serverless-application-model ${tag}\n// (${source}), Apache-2.0. Do not edit by hand.\n\n`;

const policyTemplates = await fetchJson("policy_templates_data/policy_templates.json");
const implemented = {};
const unavailable = [];
for (const [name, template] of Object.entries(policyTemplates.Templates).sort(([left], [right]) => left.localeCompare(right))) {
  const services = [...actionServices(template.Definition)];
  if (services.length && services.every(service => IMPLEMENTED_SERVICES.has(service))) implemented[name] = { Parameters: Object.keys(template.Parameters ?? {}).sort(), Definition: template.Definition };
  else unavailable.push(name);
}

const managed = await fetchJson("internal/data/aws_managed_policies.json");
const paths = {};
for (const [name, arn] of Object.entries(managed.aws).sort(([left], [right]) => left.localeCompare(right))) {
  const match = /^arn:aws:iam::aws:policy(\/.*\/|\/)([^/]+)$/.exec(arn);
  if (!match || match[2] !== name) throw new Error(`Unexpected managed policy ARN ${arn}`);
  paths[name] = match[1];
}

const schema = await fetchJson("schema/schema.json");
const definitions = schema.definitions;
const deref = (node) => node?.$ref ? definitions[node.$ref.replace("#/definitions/", "")] : node?.allOf?.length === 1 ? deref(node.allOf[0]) : node;
const resources = {};
const events = {};
for (const [key, definition] of Object.entries(definitions)) {
  const match = /^samtranslator__internal__schema_source__aws_serverless_([a-z_]+)__Resource$/.exec(key);
  if (!match) continue;
  const type = definition.properties.Type.enum[0];
  const properties = deref(definition.properties.Properties);
  resources[type] = Object.keys(properties?.properties ?? {}).sort();
  const eventSources = deref(properties?.properties?.Events)?.additionalProperties?.anyOf;
  if (eventSources) {
    events[type] = {};
    for (const source of eventSources) {
      const event = deref(source);
      events[type][event.properties.Type.enum[0]] = Object.keys(deref(event.properties.Properties)?.properties ?? {}).sort();
    }
  }
}
const globals = {};
for (const [section, node] of Object.entries(deref(schema.properties.Globals)?.properties ?? {})) globals[section] = Object.keys(deref(node)?.properties ?? {}).sort();
const sorted = (value) => Object.fromEntries(Object.entries(value).sort(([left], [right]) => left.localeCompare(right)));

await mkdir(output, { recursive: true });
await writeFile(join(output, "policy-templates.ts"), `${header("samtranslator/policy_templates_data/policy_templates.json")}export interface SamPolicyTemplate {\n  readonly Parameters: readonly string[];\n  readonly Definition: unknown;\n}\n\n/** Policy templates whose actions target only services StackSim implements. */\nexport const SAM_POLICY_TEMPLATES: Readonly<Record<string, SamPolicyTemplate>> = ${JSON.stringify(implemented, null, 2)};\n\n/** Policy templates for services StackSim does not implement. */\nexport const SAM_UNAVAILABLE_POLICY_TEMPLATES: readonly string[] = ${JSON.stringify(unavailable, null, 2)};\n`);
await writeFile(join(output, "managed-policies.ts"), `${header("samtranslator/internal/data/aws_managed_policies.json")}/** AWS managed policy name to IAM path, for the aws partition. */\nexport const AWS_MANAGED_POLICY_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(paths, null, 2)};\n`);
await writeFile(join(output, "schema.ts"), `${header("samtranslator/schema/schema.json")}/** Every property of each AWS::Serverless resource type. */\nexport const SAM_SCHEMA_RESOURCE_PROPERTIES: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sorted(resources), null, 2)};\n\n/** Every event type, and its properties, for resources that take Events. */\nexport const SAM_SCHEMA_EVENT_PROPERTIES: Readonly<Record<string, Readonly<Record<string, readonly string[]>>>> = ${JSON.stringify(sorted(Object.fromEntries(Object.entries(events).map(([type, value]) => [type, sorted(value)]))), null, 2)};\n\n/** Every Globals section and its properties. */\nexport const SAM_SCHEMA_GLOBALS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sorted(globals), null, 2)};\n`);
console.log(`policy templates: ${Object.keys(implemented).length} implemented, ${unavailable.length} unavailable; managed policies: ${Object.keys(paths).length}; resource types: ${Object.keys(resources).length}`);
